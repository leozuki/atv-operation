const VN_CHAR_REGEX = /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i;
const VN_ASCII_TRIGGER_REGEX = /(?<![\p{L}])(ktv|ca|sang\s+b\.|xem|thu|chi|kho|giao|chua|dang|da|xong|nhanh|ngay|vd|anh\s+chu\s+viet|lai\s+the\s+hai|hoai\s+trinh)(?![\p{L}])/iu;

const translationCache = new Map();

export function translateToEnglish(input) {
  if (!input || typeof input !== "string") return input;
  const trimmed = input.trim();
  if (!trimmed) return input;

  if (translationCache.has(input)) {
    return translationCache.get(input);
  }

  const leadingSpace = input.match(/^\s*/)?.[0] || "";
  const trailingSpace = input.match(/\s*$/)?.[0] || "";
  const normalized = trimmed.replace(/\s+/g, " ");

  // Tier 1: Exact Match
  if (EXACT_TRANSLATIONS[normalized]) {
    const res = leadingSpace + EXACT_TRANSLATIONS[normalized] + trailingSpace;
    translationCache.set(input, res);
    return res;
  }

  if (!VN_CHAR_REGEX.test(normalized) && !VN_ASCII_TRIGGER_REGEX.test(normalized)) {
    return input;
  }

  // Tier 2: Regex Rules
  let result = normalized;
  for (const [pattern, replacement] of REGEX_RULES) {
    result = result.replace(pattern, replacement);
  }

  if (EXACT_TRANSLATIONS[result]) {
    result = EXACT_TRANSLATIONS[result];
  } else {
    // Protect proper names before Tier 3 glossary replacement
    const usedPlaceholders = [];
    for (let i = 0; i < PROTECTED_PROPER_NAMES.length; i++) {
      const [vnName, enName] = PROTECTED_PROPER_NAMES[i];
      if (result.includes(vnName)) {
        const token = `\uE000${i}\uE001`;
        result = result.replaceAll(vnName, token);
        usedPlaceholders.push([token, enName || stripVnDiacritics(vnName)]);
      }
    }

    // Tier 3: Word-Boundary Phrase & Word Glossary
    for (const { regex, enPhrase } of COMPILED_GLOSSARY) {
      result = result.replace(regex, (match) => capitalizeLike(match, enPhrase));
    }

    // Restore protected proper names in English/romanized form
    for (const [token, enName] of usedPlaceholders) {
      result = result.replaceAll(token, enName);
    }
  }

  const finalOutput = leadingSpace + result + trailingSpace;
  if (translationCache.size < 8000) {
    translationCache.set(input, finalOutput);
  }
  return finalOutput;
}

