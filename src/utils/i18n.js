// REAL-TIME DOM TRANSLATION OBSERVER (LOSSLESS EN <-> VI SWITCHING)
// ============================================================================
let isMutatingInternal = false;

export function translateDomTree(root, lang = "en") {
  if (!root || typeof document === "undefined") return;
  isMutatingInternal = true;
  try {
    // 1. Translate Text Nodes
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    let node = walker.nextNode();
    while (node) {
      const parentTag = node.parentElement?.tagName;
      if (parentTag !== "SCRIPT" && parentTag !== "STYLE") {
        if (node.__origVnText === undefined) {
          node.__origVnText = node.nodeValue;
        } else if (lang === "en" && node.nodeValue !== node.__lastEnText) {
          node.__origVnText = node.nodeValue;
        } else if (lang !== "en" && node.__lastViText !== undefined && node.nodeValue !== node.__lastViText) {
          node.__origVnText = node.nodeValue;
        }

        if (lang === "en") {
          const translated = translateToEnglish(node.__origVnText);
          if (node.nodeValue !== translated) {
            node.nodeValue = translated;
          }
          node.__lastEnText = translated;
        } else {
          if (node.__origVnText !== undefined && node.nodeValue !== node.__origVnText) {
            node.nodeValue = node.__origVnText;
          }
          node.__lastViText = node.nodeValue;
        }
      }
      node = walker.nextNode();
    }

    // 2. Translate Attributes (placeholder, title, aria-label)
    if (root.querySelectorAll) {
      const elements = root.querySelectorAll("[placeholder], [title], [aria-label]");
      elements.forEach((el) => {
        ["placeholder", "title", "aria-label"].forEach((attr) => {
          const val = el.getAttribute(attr);
          if (!val) return;
          const origKey = `__orig_${attr}`;
          const lastEnKey = `__lastEn_${attr}`;
          const lastViKey = `__lastVi_${attr}`;
          if (el[origKey] === undefined) {
            el[origKey] = val;
          } else if (lang === "en" && val !== el[lastEnKey]) {
            el[origKey] = val;
          } else if (lang !== "en" && el[lastViKey] !== undefined && val !== el[lastViKey]) {
            el[origKey] = val;
          }

          if (lang === "en") {
            const translated = translateToEnglish(el[origKey]);
            if (val !== translated) {
              el.setAttribute(attr, translated);
            }
            el[lastEnKey] = translated;
          } else {
            if (el[origKey] !== undefined && val !== el[origKey]) {
              el.setAttribute(attr, el[origKey]);
            }
            el[lastViKey] = el.getAttribute(attr);
          }
        });
      });
    }
  } finally {
    isMutatingInternal = false;
  }
}

export function createDomLanguageObserver(root, getLang) {
  if (!root || typeof MutationObserver === "undefined") return () => {};
  let pending = false;

  const observer = new MutationObserver(() => {
    if (isMutatingInternal || pending) return;
    const lang = getLang();
    if (lang !== "en") return;
    pending = true;
    queueMicrotask(() => {
      pending = false;
      translateDomTree(root, getLang());
    });
  });

  observer.observe(root, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title"],
  });

  return () => {
    pending = false;
    observer.disconnect();
  };
}
